    private void jTable2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable2MouseClicked
        // TODO add your handling code here:
        int baris = jTable1.getSelectedRow();

        if (baris != -1) {
         
            if (jTable1.getValueAt(baris, 1) != null) {
                jTextField1.setText(jTable1.getValueAt(baris, 1).toString());
            }

            if (jTable1.getValueAt(baris, 2) != null) {
                String jk = jTable1.getValueAt(baris, 2).toString();
                jComboBox1.setSelectedItem(jk);
            }

            if (jTable1.getValueAt(baris, 3) != null) {
                try {
                    String tanggalStr = jTable1.getValueAt(baris, 3).toString();
                    java.util.Date tanggal = new java.text.SimpleDateFormat("yyyy-MM-dd").parse(tanggalStr);
                    jDateChooser1.setDate(tanggal);
                } catch (Exception e) {
                    jDateChooser1.setDate(null);
                }
            }

            if (jTable1.getValueAt(baris, 4) != null) {
                jTextArea1.setText(jTable1.getValueAt(baris, 4).toString());
            }
        }
    }//GEN-LAST:event_jTable2MouseClicked

