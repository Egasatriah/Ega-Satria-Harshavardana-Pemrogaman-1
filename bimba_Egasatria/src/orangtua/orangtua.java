    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (jTextField1.getText().trim().isEmpty() || 
            jTextField2.getText().trim().isEmpty() || 
            jTextField3.getText().trim().isEmpty() || 
            jTextArea1.getText().trim().isEmpty()) {
            
            JOptionPane.showMessageDialog(this, 
                    "Semua kolom wajib diisi!", 
                    "Peringatan Validasi", 
                    JOptionPane.WARNING_MESSAGE);
            return; 
        }
        
        try {
            Connection conn = koneksi.getConnection();
            String sql = "INSERT INTO orang_tua (nama_ayah, nama_ibu, no_hp, alamat) VALUES (?, ?, ?, ?)";
            PreparedStatement pst = conn.prepareStatement(sql);
            
            pst.setString(1, jTextField1.getText().trim());
            pst.setString(2, jTextField2.getText().trim());
            pst.setString(3, jTextField3.getText().trim());
            pst.setString(4, jTextArea1.getText().trim());
            
            int hasil = pst.executeUpdate();
            
            if (hasil > 0) {
                JOptionPane.showMessageDialog(this, "Data Orang Tua berhasil disimpan!", "Informasi", JOptionPane.INFORMATION_MESSAGE);
                tampilData(); 
                jButton5ActionPerformed(evt); // Ini memanggil tombol Clear secara otomatis
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data!\nError: " + e.getMessage(), "Error Sistem", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        try {
            if (idOrangTua.equals("")) {
                JOptionPane.showMessageDialog(null, "Pilih data yang akan dihapus!");
                return;
            }
            
            int konfirmasi = JOptionPane.showConfirmDialog(null, "Yakin ingin menghapus data ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
            if (konfirmasi == JOptionPane.YES_OPTION) {
                Connection conn = koneksi.getConnection();
                String sql = "DELETE FROM orang_tua WHERE id_orangtua=?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, idOrangTua);
                
                pst.executeUpdate();
                JOptionPane.showMessageDialog(null, "Data Berhasil Dihapus");
                
                tampilData();
                jButton5ActionPerformed(evt); // Memanggil tombol Clear
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal menghapus data: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        try {
            if (idOrangTua.equals("")) {
                JOptionPane.showMessageDialog(null, "Pilih data di tabel yang ingin diubah terlebih dahulu!");
                return;
            }
            
            Connection conn = koneksi.getConnection();
            String sql = "UPDATE orang_tua SET nama_ayah=?, nama_ibu=?, no_hp=?, alamat=? WHERE id_orangtua=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, jTextField1.getText());
            pst.setString(2, jTextField2.getText());
            pst.setString(3, jTextField3.getText());
            pst.setString(4, jTextArea1.getText());
            pst.setString(5, idOrangTua);
            
            pst.executeUpdate();
            JOptionPane.showMessageDialog(null, "Data Berhasil Diperbarui");
            
            tampilData();
            jButton5ActionPerformed(evt); // Memanggil tombol Clear
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal memperbarui data: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton3ActionPerformed

