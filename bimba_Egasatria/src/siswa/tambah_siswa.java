    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        int baris = jTable2.getSelectedRow();
        if (baris == -1) {
            JOptionPane.showMessageDialog(this, "Silakan pilih data pada tabel yang ingin dihapus.", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String idSiswa = jTable2.getValueAt(baris, 0).toString();
        int konfirmasi = JOptionPane.showConfirmDialog(this, 
                "Apakah Anda yakin ingin menghapus data siswa ini?", 
                "Konfirmasi Hapus", 
                JOptionPane.YES_NO_OPTION, 
                JOptionPane.QUESTION_MESSAGE);

        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                Connection conn = koneksi.getConnection();
                String sql = "DELETE FROM siswa WHERE id_siswa=?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, idSiswa);

                pst.executeUpdate();
                JOptionPane.showMessageDialog(this, "Data berhasil dihapus.", "Informasi", JOptionPane.INFORMATION_MESSAGE);

                tampilData();               
                jButton4ActionPerformed(evt); 

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Terjadi kesalahan saat menghapus data: " + e.getMessage(), "Kesalahan", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
    int baris = jTable2.getSelectedRow();
    // Pastikan baris sudah dipilih
    if (baris == -1) {
        JOptionPane.showMessageDialog(this, "Silakan pilih data pada tabel terlebih dahulu.", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Validasi nama siswa
    if (jTextField1.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Nama siswa tidak boleh kosong.", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Validasi tanggal agar tidak terjadi NullPointerException
    if (jDateChooser1.getDate() == null) {
        JOptionPane.showMessageDialog(this, "Tanggal lahir tidak boleh kosong.", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // PERBAIKAN: Gunakan jTable2 secara konsisten
    String idSiswa = jTable2.getValueAt(baris, 0).toString();

    try {
        Connection conn = koneksi.getConnection();
        String sql = "UPDATE siswa SET nama_siswa=?, jenis_kelamin=?, tanggal_lahir=?, alamat_siswa=? WHERE id_siswa=?";
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setString(1, jTextField1.getText());
        pst.setString(2, jComboBox1.getSelectedItem().toString());

        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String tanggal = sdf.format(jDateChooser1.getDate());
        pst.setString(3, tanggal);

        pst.setString(4, jTextArea1.getText());
        pst.setString(5, idSiswa); 

        // Eksekusi query
        int barisTerdampak = pst.executeUpdate();

        if (barisTerdampak > 0) {
            JOptionPane.showMessageDialog(this, "Data berhasil diperbarui.", "Informasi", JOptionPane.INFORMATION_MESSAGE);
            tampilData();                
            jButton4ActionPerformed(evt); 
        } else {
            JOptionPane.showMessageDialog(this, "Gagal memperbarui data. ID tidak ditemukan.", "Peringatan", JOptionPane.WARNING_MESSAGE);
        }

        // Praktik yang baik: Tutup koneksi agar tidak memory leak
        pst.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Terjadi kesalahan sistem: " + e.getMessage(), "Kesalahan", JOptionPane.ERROR_MESSAGE);
        e.printStackTrace(); // Tambahkan ini untuk melihat detail error di console (Netbeans/Eclipse)
        }
        
    }//GEN-LAST:event_jButton2ActionPerformed

